// Converts the news articles in content/news/*.yml (edited by hand or through Decap CMS at /admin)
// into src/app/core/content/news.generated.ts, which the app imports.
// Runs automatically before `npm start`, `npm run build` and `npm test`.
//
// Each file holds one article in all languages (Decap's i18n "single_file" structure):
//   sr: { title, slug, date, topic, image?, summary, body }   ← Serbian is the main language
//   en: { title, summary, body, ... }
//   de: { ... }
// Missing translations fall back to Serbian, so an article can be published before it is translated.

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { marked } from 'marked';
import { parse } from 'yaml';

const ROOT = join(import.meta.dirname, '..');
const CONTENT_DIR = join(ROOT, 'content', 'news');
const OUTPUT = join(ROOT, 'src', 'app', 'core', 'content', 'news.generated.ts');

const LANGUAGES = ['sr', 'en', 'de'];
const MAIN_LANG = 'sr';
const TOPICS = ['food', 'heating', 'education', 'health', 'community'];
const SLUG_PATTERN = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

const errors = [];
const warnings = [];

function toDate(value) {
  const date = value instanceof Date ? value.toISOString() : String(value ?? '');
  return /^\d{4}-\d{2}-\d{2}/.test(date) ? date.slice(0, 10) : null;
}

function text(value) {
  return typeof value === 'string' ? value.trim() : '';
}

function readArticle(file) {
  const data = parse(readFileSync(join(CONTENT_DIR, file), 'utf8')) ?? {};
  const main = data[MAIN_LANG] ?? {};
  const fail = (message) => errors.push(`${file}: ${message}`);

  const slug = text(main.slug);
  const date = toDate(main.date);
  const topic = text(main.topic) || 'community';
  const image = text(main.image) || undefined;

  if (!SLUG_PATTERN.test(slug)) fail(`"slug" must use lowercase latin letters, digits and dashes (got "${slug}")`);
  if (!date) fail(`"date" must be a date like 2026-11-17 (got "${main.date}")`);
  if (!TOPICS.includes(topic)) fail(`"topic" must be one of ${TOPICS.join(', ')} (got "${topic}")`);
  for (const field of ['title', 'summary', 'body']) {
    if (!text(main[field])) fail(`Serbian "${field}" is required`);
  }

  const localized = (field, transform = (value) => value) =>
    Object.fromEntries(
      LANGUAGES.map((lang) => {
        let value = text(data[lang]?.[field]);
        if (!value) {
          if (lang !== MAIN_LANG) warnings.push(`${file}: no ${lang.toUpperCase()} "${field}" – showing Serbian`);
          value = text(main[field]);
        }
        return [lang, transform(value)];
      }),
    );

  return {
    slug,
    date,
    topic,
    ...(image && { image }),
    title: localized('title'),
    summary: localized('summary'),
    body: localized('body', (markdown) => marked.parse(markdown, { async: false })),
  };
}

const files = readdirSync(CONTENT_DIR).filter((file) => /\.ya?ml$/.test(file));
const articles = files.map(readArticle);

const seen = new Map();
articles.forEach((article, i) => {
  if (seen.has(article.slug)) errors.push(`${files[i]}: slug "${article.slug}" is already used by ${seen.get(article.slug)}`);
  seen.set(article.slug, files[i]);
});

warnings.forEach((warning) => console.warn(`[news] warning: ${warning}`));
if (errors.length) {
  errors.forEach((error) => console.error(`[news] error: ${error}`));
  process.exit(1);
}

articles.sort((a, b) => b.date.localeCompare(a.date) || a.slug.localeCompare(b.slug));

writeFileSync(
  OUTPUT,
  `// GENERATED by scripts/build-news.mjs from content/news – do not edit, changes will be overwritten.\n` +
    `import type { NewsItem } from './news';\n\n` +
    `export const NEWS_ITEMS: NewsItem[] = ${JSON.stringify(articles, null, 2)};\n`,
);
console.log(`[news] ${articles.length} article(s) → ${OUTPUT.replace(ROOT + '/', '')}`);
